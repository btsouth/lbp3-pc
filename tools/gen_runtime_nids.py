#!/usr/bin/env python3
"""Write src/import_names_runtime.inc: the NID of every name in the runtime's export tables.

A NID is a hash of the symbol name, so a game that imports a function the runtime has (under
another library, or one Bloodborne never imported) finds it by name. Names already in
src/import_names.inc are left out. Run after adding names to a RuntimeExport table.
"""
import base64
import hashlib
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parent.parent
KEY = bytes.fromhex('518d64a635ded8c1e6b039b1c3e55230')


def nid(name):
    digest = hashlib.sha1(name.encode() + KEY).digest()[:8]
    value = struct.unpack('<Q', digest)[0]
    return base64.b64encode(struct.pack('>Q', value)).decode().rstrip('=').replace('/', '-')


def main():
    known = {n.split('#')[0] for n in re.findall(r'\{"([^"]+)","[^"]*"\}', (ROOT / 'src/import_names.inc').read_text())}
    names = set()
    for source in sorted((ROOT / 'src').glob('runtime*.c')):
        for table in re.findall(r'RuntimeExport exports\[\]=\{(.*?)\n\};', source.read_text(), re.S):
            names.update(re.findall(r'\{"([^"]+)",', table))
    lines = [f'{{"{nid(n)}#runtime","{n}"}},' for n in sorted(names) if nid(n) not in known]
    header = ('/* Generated by tools/gen_runtime_nids.py: NIDs of the runtime export tables\' names\n'
              ' * that src/import_names.inc does not list. */\n')
    (ROOT / 'src/import_names_runtime.inc').write_text(header + '\n'.join(lines) + '\n')
    print(f'{len(lines)} names ({len(names)} exported, the others already listed)')


if __name__ == '__main__':
    main()
